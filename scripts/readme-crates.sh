#!/usr/bin/env bash
# Generate the README crate table from package metadata (ADR 0010 tiers).
#
# Usage:
#   bash scripts/readme-crates.sh          # rewrite the table between the README markers
#   bash scripts/readme-crates.sh --check  # exit 1 if README is out of date (CI)
# Requires: cargo, jq.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
README="README.md"
BEGIN='<!-- crates:begin (generated by scripts/readme-crates.sh; do not edit) -->'
END='<!-- crates:end -->'

packages() { # manifest-path
    cargo metadata --no-deps --format-version 1 --manifest-path "$1" |
    jq -r --arg root "$ROOT/" '.packages[]
      | [(.metadata.id_effect.tier // "-"), .name, (.manifest_path | ltrimstr($root) | rtrimstr("/Cargo.toml")),
         ((.description // "") | gsub("\\|"; "\\|") | gsub("\n"; " "))] | @tsv'
}

rows="$(packages Cargo.toml)"
if [[ -f labs/Cargo.toml ]]; then
    rows+=$'\n'"$(packages labs/Cargo.toml)"
fi

table() {
    local tier title badge
    for spec in "core|Core" "runtime|Runtime and supervision" "integration|Integrations" "platform|Platform (batteries)" "maintenance|Maintenance (frozen API)" "labs|Labs (unpublished, no guarantees)"; do
        tier="${spec%%|*}"
        title="${spec#*|}"
        local section
        section="$(awk -F'\t' -v t="$tier" '$1 == t' <<<"$rows" | sort -t$'\t' -k2,2)"
        [[ -z "$section" ]] && continue
        printf '\n**%s**\n\n| Crate | Version | Description |\n|-------|---------|-------------|\n' "$title"
        while IFS=$'\t' read -r _ name path desc; do
            if [[ "$tier" == labs ]]; then
                badge="unpublished"
            else
                badge="[![crates.io](https://img.shields.io/crates/v/$name.svg)](https://crates.io/crates/$name)"
            fi
            printf '| [`%s`](%s) | %s | %s |\n' "$name" "$path" "$badge" "$desc"
        done <<<"$section"
    done
    printf '\nTiers and their quality bar: [ADR 0010](docs/adrs/0010-crate-tiers.md), [docs/QUALITY_BAR.md](docs/QUALITY_BAR.md).\n'
}

generated="$(table)"

if ! grep -qF "$BEGIN" "$README" || ! grep -qF "$END" "$README"; then
    echo "readme-crates: markers not found in $README" >&2
    exit 2
fi

new="$(awk -v begin="$BEGIN" -v end="$END" -v body="$generated" '
  index($0, begin) == 1 { print; print body; skip = 1; next }
  index($0, end) == 1 { skip = 0 }
  !skip { print }
' "$README")"

if [[ "${1:-}" == "--check" ]]; then
    if [[ "$new" != "$(cat "$README")" ]]; then
        echo "readme-crates: README crate table is stale; run: bash scripts/readme-crates.sh" >&2
        exit 1
    fi
    echo "readme-crates: up to date"
else
    printf '%s\n' "$new" > "$README"
    echo "readme-crates: README updated"
fi
