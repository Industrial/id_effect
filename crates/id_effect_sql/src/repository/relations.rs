/// A [`Repository`] that loads relations with its rows ([`Repository::with`]): the reads, each
/// returning [`Loaded`] entities. Writes stay on the [`Repository`].
pub struct EagerRepository<T> {
  repo: Repository<T>,
  loaders: Vec<Arc<dyn Loader<T>>>,
}

impl<T> Clone for EagerRepository<T> {
  fn clone(&self) -> Self {
    Self {
      repo: self.repo.clone(),
      loaders: self.loaders.clone(),
    }
  }
}

impl<T> fmt::Debug for EagerRepository<T> {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.debug_struct("EagerRepository")
      .field("repository", &self.repo)
      .field(
        "relations",
        &self.loaders.iter().map(|l| l.name()).collect::<Vec<_>>(),
      )
      .finish()
  }
}

/// An [`EagerRepository`] bound to one executor ([`EagerRepository::on`],
/// [`BoundRepository::with`]): the same reads as environment-free effects.
pub struct BoundEagerRepository<T> {
  eager: EagerRepository<T>,
  ex: Arc<dyn SqlExecutor>,
}

impl<T> Clone for BoundEagerRepository<T> {
  fn clone(&self) -> Self {
    Self {
      eager: self.eager.clone(),
      ex: Arc::clone(&self.ex),
    }
  }
}

impl<T> fmt::Debug for BoundEagerRepository<T> {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.debug_tuple("BoundEagerRepository")
      .field(&self.eager)
      .finish()
  }
}

impl<T: Entity> Repository<T> {
  /// This repository's reads, also loading `rel` for every row returned (one query per
  /// relation per level; see [`Relation`]). Chain [`EagerRepository::with`] for more.
  pub fn with<C: Entity + Clone + Sync>(&self, rel: Relation<T, C>) -> EagerRepository<T> {
    EagerRepository {
      repo: self.clone(),
      loaders: Vec::new(),
    }
    .with(rel)
  }
}

impl<T: Entity> BoundRepository<T> {
  /// [`Repository::with`] on this executor.
  pub fn with<C: Entity + Clone + Sync>(&self, rel: Relation<T, C>) -> BoundEagerRepository<T> {
    BoundEagerRepository {
      eager: self.repo.with(rel),
      ex: Arc::clone(&self.ex),
    }
  }
}

impl<T: Entity> EagerRepository<T> {
  /// Also load `rel` (a relation of the same name replaces the earlier one).
  #[must_use]
  pub fn with<C: Entity + Clone + Sync>(mut self, rel: Relation<T, C>) -> Self {
    add_loader(&mut self.loaders, rel);
    self
  }

  /// The repository the rows are read with (its tenant and filters also scope the relations).
  #[inline]
  pub fn repository(&self) -> &Repository<T> {
    &self.repo
  }

  /// The names of the relations loaded.
  pub fn relations(&self) -> Vec<&'static str> {
    self.loaders.iter().map(|l| l.name()).collect()
  }

  /// The levels loaded (the deepest relation chain).
  pub fn depth(&self) -> usize {
    max_depth(&self.loaders)
  }

  /// The same reads on `executor`, e.g. a transaction.
  pub fn on(&self, executor: impl SqlExecutor) -> BoundEagerRepository<T> {
    BoundEagerRepository {
      eager: self.clone(),
      ex: Arc::new(executor),
    }
  }

  /// `base`, then the relations of its rows, then `finish`.
  fn eager<A: Send + 'static>(
    &self,
    base: Result<Run<Vec<T>>, SqlError>,
    finish: fn(Vec<Loaded<T>>) -> A,
  ) -> Result<Run<A>, SqlError> {
    let depth = self.depth();
    if depth > MAX_EAGER_DEPTH {
      return Err(SqlError::Unsupported(format!(
        "entity `{}`: eager loading nests {depth} relation levels, at most {MAX_EAGER_DEPTH} \
         are loaded",
        T::NAME
      )));
    }
    self.loaders.iter().try_for_each(|l| l.check(&self.repo))?;
    let base = base?;
    let (repo, loaders) = (self.repo.clone(), self.loaders.clone());
    Ok(Box::new(move |ex| {
      base(Arc::clone(&ex)).flat_map(move |rows| {
        let parents = rows.into_iter().map(Loaded::new).collect();
        load_all(ex, repo, parents, loaders.into()).map(finish)
      })
    }))
  }

  fn find_op(&self, id: &T::Id) -> Result<Run<Option<Loaded<T>>>, SqlError> {
    let base = self
      .repo
      .select(Repository::<T>::id_is(id))
      .and_then(|mut stmt| self.repo.render(&*stmt.limit(1)))
      .map(|stmt| rows(stmt, |rows| from_rows(&rows)));
    self.eager(base, |found| found.into_iter().next())
  }

  fn find_by_op(
    &self,
    cond: Condition,
    page: Option<Page>,
  ) -> Result<Run<Vec<Loaded<T>>>, SqlError> {
    self.eager(self.repo.find_by_op(cond, page), |loaded| loaded)
  }

  fn load_op(&self, entities: Vec<T>) -> Result<Run<Vec<Loaded<T>>>, SqlError> {
    self.eager(Ok(Box::new(move |_| succeed(entities))), |loaded| loaded)
  }
}

impl<T: Entity> BoundEagerRepository<T> {
  /// Also load `rel`.
  #[must_use]
  pub fn with<C: Entity + Clone + Sync>(self, rel: Relation<T, C>) -> Self {
    Self {
      eager: self.eager.with(rel),
      ex: self.ex,
    }
  }

  /// The eager repository this is bound from.
  #[inline]
  pub fn eager_repository(&self) -> &EagerRepository<T> {
    &self.eager
  }

  fn run<A: Send + 'static>(&self, op: Result<Run<A>, SqlError>) -> Effect<A, SqlError> {
    match op {
      Ok(run) => run(Arc::clone(&self.ex)),
      Err(e) => id_effect::fail(e),
    }
  }
}

/// The eager reads, once: [`EagerRepository`] runs them on the client in the environment,
/// [`BoundEagerRepository`] on its executor.
macro_rules! eager_operations {
  ($(
    $(#[$doc:meta])*
    fn $name:ident($($arg:ident: $ty:ty),*) -> $ret:ty = $op:ident($($call:expr),*);
  )*) => {
    impl<T: Entity> EagerRepository<T> {
      $(
        $(#[$doc])*
        pub fn $name<R, I>(&self, $($arg: $ty),*) -> Effect<$ret, SqlError, R>
        where
          R: Selector<SqlClientService, I> + HList,
        {
          Repository::<T>::in_env(self.$op($($call),*))
        }
      )*
    }

    impl<T: Entity> BoundEagerRepository<T> {
      $(
        $(#[$doc])*
        pub fn $name(&self, $($arg: $ty),*) -> Effect<$ret, SqlError> {
          self.run(self.eager.$op($($call),*))
        }
      )*
    }
  };
}

eager_operations! {
  /// The row with primary key `id` and its relations, or `None` (also when a filter hides it).
  fn find(id: T::Id) -> Option<Loaded<T>> = find_op(&id);
  /// Every row the filters let through, in primary-key order, with its relations.
  fn find_all() -> Vec<Loaded<T>> = find_by_op(Condition::all(), None);
  /// The rows matching `cond`, in primary-key order, with their relations.
  fn find_by(cond: impl IntoCondition) -> Vec<Loaded<T>> =
    find_by_op(cond.into_condition(), None);
  /// One [`Page`] of the rows matching `cond`, in primary-key order, with their relations.
  fn find_page(cond: impl IntoCondition, page: Page) -> Vec<Loaded<T>> =
    find_by_op(cond.into_condition(), Some(page));
  /// The relations of `entities` already read (e.g. one keyset page), in their order; only the
  /// relation queries run.
  fn load(entities: Vec<T>) -> Vec<Loaded<T>> = load_op(entities);
}

#[cfg(test)]
mod tests {
  use super::*;
  use crate::query_builder::Dialect;

  #[derive(Clone, Debug, PartialEq)]
  struct Order {
    id: i64,
    customer_id: Option<i64>,
  }

  impl FromRow for Order {
    fn from_row(row: &SqlRow) -> Result<Self, SqlError> {
      Ok(Self {
        id: row.get("id")?,
        customer_id: row.get("customer_id")?,
      })
    }
  }

  impl Entity for Order {
    type Id = i64;
    const NAME: &'static str = "Order";
    const TABLE: &'static str = "orders";
    const COLUMNS: &'static [&'static str] = &["id", "customer_id"];
    const ID: &'static str = "id";
    const TENANT: Option<&'static str> = Some("org_id");

    fn id(&self) -> i64 {
      self.id
    }

    fn values(&self) -> Vec<(&'static str, SqlValue)> {
      vec![
        ("id", self.id.to_sql_value()),
        ("customer_id", self.customer_id.to_sql_value()),
      ]
    }
  }

  #[derive(Clone, Debug, PartialEq)]
  struct Tag {
    id: i64,
  }

  impl FromRow for Tag {
    fn from_row(row: &SqlRow) -> Result<Self, SqlError> {
      Ok(Self { id: row.get("id")? })
    }
  }

  impl Entity for Tag {
    type Id = i64;
    const NAME: &'static str = "Tag";
    const TABLE: &'static str = "tags";
    const COLUMNS: &'static [&'static str] = &["id"];
    const ID: &'static str = "id";
    const SOFT_DELETE: Option<&'static str> = Some("deleted_at");
    const TENANT: Option<&'static str> = Some("org_id");

    fn id(&self) -> i64 {
      self.id
    }

    fn values(&self) -> Vec<(&'static str, SqlValue)> {
      vec![("id", self.id.to_sql_value())]
    }
  }

  fn tags() -> Relation<Order, Tag> {
    Relation::many_to_many("tags", "order_tags", "order_id", "tag_id")
  }

  #[test]
  fn defaults_and_metadata() {
    assert_eq!(Order::LABEL, "Order");
    assert!(Order::FIELDS.is_empty() && Order::RELATIONS.is_empty());
    let meta = tags().meta();
    assert_eq!(
      (meta.name, meta.target, meta.target_table),
      ("tags", "Tag", "tags")
    );
    let field = FieldMeta::new("customer_id", "customer_id", "i64")
      .nullable(true)
      .relation("customer");
    assert_eq!(
      (field.label, field.nullable, field.editable, field.relation),
      ("customer_id", true, false, Some("customer"))
    );
  }

  #[test]
  fn many_to_many_qualifies_the_child_filters_in_every_dialect() {
    let repo = Repository::<Tag>::new(Dialect::Postgres).with_tenant(7i64);
    let (sql, params) = tags()
      .statement(&repo, &[SqlValue::I64(1), SqlValue::I64(2)])
      .unwrap();
    assert_eq!(
      sql,
      r#"SELECT "tags"."id", "order_tags"."order_id" AS "__id_effect_key" FROM "tags" INNER JOIN "order_tags" ON "order_tags"."tag_id" = "tags"."id" WHERE "tags"."org_id" = $1 AND "tags"."deleted_at" IS NULL AND "order_tags"."order_id" IN ($2, $3) ORDER BY "tags"."id" ASC"#
    );
    assert_eq!(
      params,
      [SqlValue::I64(7), SqlValue::I64(1), SqlValue::I64(2)]
    );
    let mysql = Repository::<Tag>::new(Dialect::MySql).with_tenant(7i64);
    let (sql, _) = tags().statement(&mysql, &[SqlValue::I64(1)]).unwrap();
    assert!(
      sql.contains("INNER JOIN `order_tags` ON `order_tags`.`tag_id` = `tags`.`id`"),
      "{sql}"
    );
    let sqlite = Repository::<Tag>::new(Dialect::Sqlite).unscoped();
    let (sql, _) = tags().statement(&sqlite, &[SqlValue::I64(1)]).unwrap();
    assert!(sql.ends_with(r#"WHERE "order_tags"."order_id" IN (?) ORDER BY "tags"."id" ASC"#));
  }

  #[test]
  fn belongs_to_needs_the_foreign_key_field() {
    let rel = Relation::<Order, Tag>::belongs_to("tag", "tag_id");
    let err = rel
      .parent_key(&Order {
        id: 1,
        customer_id: None,
      })
      .unwrap_err();
    assert!(
      matches!(&err, SqlError::Unsupported(m) if m.contains("has no column `tag_id`")),
      "{err:?}"
    );
    let customer = Relation::<Order, Tag>::belongs_to("customer", "customer_id");
    let order = |customer_id| Order { id: 1, customer_id };
    assert_eq!(customer.parent_key(&order(None)), Ok(None));
    assert_eq!(
      customer.parent_key(&order(Some(4))),
      Ok(Some(SqlValue::I64(4)))
    );
  }

  #[test]
  fn keys_are_chunked_and_deduplicated() {
    let repo = Repository::<Tag>::new(Dialect::Sqlite).with_tenant(1i64);
    let parents: Vec<_> = (0..2_500)
      .map(|i| {
        Loaded::new(Order {
          id: i % 2_100,
          customer_id: None,
        })
      })
      .collect();
    let (keys, stmts) = tags().prepare(&repo, &parents).unwrap();
    assert_eq!((keys.len(), stmts.len()), (2_500, 3));
    assert_eq!(
      stmts[2].1.len(),
      1 + 100,
      "the tenant, then the last 100 keys"
    );
    let unscoped = Repository::<Tag>::new(Dialect::Sqlite);
    assert!(matches!(
      tags().prepare(&unscoped, &[]),
      Err(SqlError::Unsupported(m)) if m.contains("no tenant")
    ));
  }

  #[test]
  fn attach_shares_and_moves_children() {
    let rel = tags();
    let parents = vec![
      Loaded::new(Order {
        id: 1,
        customer_id: None,
      }),
      Loaded::new(Order {
        id: 2,
        customer_id: None,
      }),
      Loaded::new(Order {
        id: 1,
        customer_id: None,
      }),
      Loaded::new(Order {
        id: 3,
        customer_id: None,
      }),
    ];
    let key = |n: i64| Key::of(&SqlValue::I64(n));
    let keys = [Some(key(1)), Some(key(2)), Some(key(1)), None];
    let owners = vec![key(1), key(1), key(2)];
    let children = vec![
      Loaded::new(Tag { id: 10 }),
      Loaded::new(Tag { id: 11 }),
      Loaded::new(Tag { id: 12 }),
    ];
    let loaded = attach("tags", parents, &keys, owners, children);
    let ids = |o: &Loaded<Order>| o.get(&rel).iter().map(|t| t.id).collect::<Vec<_>>();
    assert_eq!(ids(&loaded[0]), [10, 11]);
    assert_eq!(ids(&loaded[1]), [12]);
    assert_eq!(ids(&loaded[2]), [10, 11], "a shared key clones");
    assert_eq!(ids(&loaded[3]), [] as [i64; 0]);
    assert_eq!(loaded[3].relations(), ["tags"]);
    assert_eq!(loaded[1].one(&rel).map(|t| t.id), Some(12));
    let other = Relation::<Order, Order>::has_many("tags", "x");
    assert!(
      loaded[0].try_get(&other).is_none(),
      "a name of another type"
    );
    let copy = loaded[0].clone();
    assert_eq!(copy.entity(), loaded[0].entity());
    assert!(format!("{copy:?}").contains("relations: [\"tags\"]"));
    assert_eq!(copy.into_entity().id, 1);
  }

  #[test]
  fn relations_nest_debug_and_dedupe() {
    let deep = Relation::<Tag, Order>::has_many("orders", "tag_id").with(tags());
    assert_eq!((deep.depth(), deep.relations()), (2, vec!["tags"]));
    let deep = deep.with(tags());
    assert_eq!(deep.relations(), ["tags"], "same name replaces");
    assert!(format!("{:?}", deep.clone()).contains("nested: [\"tags\"]"));
    let eager = Repository::<Tag>::new(Dialect::Postgres)
      .with(deep.clone())
      .with(deep);
    assert_eq!((eager.relations(), eager.depth()), (vec!["orders"], 2));
    assert!(format!("{eager:?}").contains("relations: [\"orders\"]"));
    let client: Arc<dyn crate::SqlClient> = Arc::new(crate::TestSqlClient::new());
    let bound = eager.on(client);
    assert!(format!("{:?}", bound.clone()).starts_with("BoundEagerRepository"));
    assert_eq!(bound.eager_repository().relations(), ["orders"]);
    assert_eq!(
      bound.eager_repository().repository().dialect(),
      Dialect::Postgres
    );
  }

  fn failure<A: fmt::Debug + Send + 'static>(eff: Effect<A, SqlError>) -> SqlError {
    match eff.block_on() {
      id_effect::Exit::Failure(id_effect::Cause::Fail(e)) => e,
      other => panic!("expected a failure, got {other:?}"),
    }
  }

  #[test]
  fn relation_errors_fail_the_effect() {
    let test = crate::TestSqlClient::new();
    assert!(matches!(
      crate::SqlClient::connect(&test).block_on(),
      id_effect::Exit::Success(())
    ));
    let client: Arc<dyn crate::SqlClient> = Arc::new(test.clone());
    test.script_query(
      r#"SELECT "id", "customer_id" FROM "orders" WHERE "org_id" = $1 ORDER BY "id" ASC"#,
      vec![SqlRow::from_pairs([
        ("id", SqlValue::I64(1)),
        ("customer_id", SqlValue::I64(2)),
      ])],
    );
    let orders = Repository::<Order>::new(Dialect::Postgres).with_tenant(1i64);
    // A belongs_to foreign key that is not a column of the parent.
    let bad = Relation::<Order, Tag>::belongs_to("tag", "tag_id");
    let err = failure(orders.on(Arc::clone(&client)).with(bad).find_all());
    assert!(matches!(err, SqlError::Unsupported(m) if m.contains("tag_id")));
    // A child row without its owner key.
    test.script_query(
      r#"SELECT "id", "id" AS "__id_effect_key" FROM "tags" WHERE "org_id" = $1 AND "deleted_at" IS NULL AND "id" IN ($2) ORDER BY "id" ASC"#,
      vec![SqlRow::from_pairs([("id", SqlValue::I64(2))])],
    );
    let tag = Relation::<Order, Tag>::belongs_to("tag", "customer_id");
    let err = failure(
      orders
        .on(Arc::clone(&client))
        .with(tags())
        .with(tag.clone())
        .find_all(),
    );
    assert_eq!(
      err,
      SqlError::ColumnNotFound {
        column: KEY.to_owned()
      }
    );
    // The query itself failing.
    test.fail_queries("down");
    let err = failure(orders.on(client).with(tag).find_all());
    assert!(matches!(err, SqlError::QueryFailed { .. }), "{err:?}");
  }
}
