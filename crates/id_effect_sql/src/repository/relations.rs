//! Relations between entities, eager loading ([`Repository::with`]) and the field and relation
//! metadata of [`Entity`] ([`FieldMeta`], [`RelationMeta`]).
//!
//! A [`Relation<P, C>`] leads from a parent entity `P` to child entities `C`:
//!
//! | Kind | Declared on `P` as | Children are the `C` rows whose … |
//! |---|---|---|
//! | [`belongs_to`](Relation::belongs_to) (N:1) | `belongs_to(C, foreign_key = "c_id")` | primary key is `P`'s `c_id` |
//! | [`has_many`](Relation::has_many) (1:N) | `has_many(C, foreign_key = "p_id")` | `p_id` is `P`'s primary key |
//! | [`many_to_many`](Relation::many_to_many) (N:M) | `many_to_many(C, through = "p_c")` | primary key is paired with `P`'s in the join table `p_c` |
//!
//! [`Repository::with`] loads the children of every parent row in **one `IN (…)` query per
//! relation per level** (the keys of all parents at once, never one query per row), then the
//! nested relations of those children ([`Relation::with`]) the same way, at most
//! [`MAX_EAGER_DEPTH`] levels deep. Keys are deduplicated and sent in chunks of 1 000 so a
//! statement stays within every driver's parameter limit.
//!
//! **Secure by default** (ADR 0013 R1): children are read the way the parent repository reads
//! (same dialect, tenant and filter mode), so the child entity's own tenant, soft-delete and
//! custom filters are AND-ed into the relation query, inside the join for `many_to_many`. A
//! foreign key or join-table row pointing at another tenant's row loads nothing; a tenant-scoped
//! child under a repository without a tenant fails closed ([`SqlError::Unsupported`]).
//! [`Repository::unscoped`] lifts the filters of the children too.

