/// How many relation levels [`Repository::with`] loads at most (`a → b → c`); a deeper chain
/// fails with [`SqlError::Unsupported`] before any query runs.
pub const MAX_EAGER_DEPTH: usize = 3;

/// The most keys one relation query carries (portable across driver parameter limits).
const IN_CHUNK: usize = 1000;

/// The alias of the owner key every relation query selects next to the child's columns.
const KEY: &str = "__id_effect_key";

// ---- metadata ----

/// What one field of an entity is: [`Entity::FIELDS`], generated by `#[derive(Entity)]` for
/// generic tools (an admin's lists and forms, exports).
///
/// Build one with [`FieldMeta::new`] and the `const` setters (a hand-written impl can list its
/// fields in a `const`).
///
/// ```rust
/// use id_effect_sql::repository::FieldMeta;
///
/// const NAME: FieldMeta = FieldMeta::new("name", "display_name", "String")
///   .editable(true)
///   .label("account.name");
/// assert_eq!((NAME.column, NAME.nullable, NAME.editable), ("display_name", false, true));
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct FieldMeta {
  /// The Rust field name.
  pub name: &'static str,
  /// The column (the `FromRow` column: `#[from_row(rename)]`, else `#[schema("..")]`, else the
  /// field name).
  pub column: &'static str,
  /// The type its `Schema` / `FromSqlValue` decodes, as written in the struct without the outer
  /// `Option` (`"i64"`, `"String"`, `"jiff::Timestamp"`).
  pub schema_type: &'static str,
  /// Whether the field is an `Option` (the column admits NULL).
  pub nullable: bool,
  /// Whether a generic form may bind it (`#[entity(editable)]`). Off by default: only declared
  /// fields are ever written from user input (no mass assignment).
  pub editable: bool,
  /// The label key (`#[entity(label = "..")]`, by default `"<entity>.<field>"` in snake case),
  /// e.g. a translation key.
  pub label: &'static str,
  /// The [`belongs_to`](Relation::belongs_to) relation this field is the foreign key of: its
  /// name in [`Entity::RELATIONS`], whose [`RelationMeta::target`] is the referenced entity.
  pub relation: Option<&'static str>,
}

impl FieldMeta {
  /// The field `name` stored in `column`, of type `schema_type`: not nullable, not editable,
  /// labelled `name`, no relation.
  pub const fn new(name: &'static str, column: &'static str, schema_type: &'static str) -> Self {
    Self {
      name,
      column,
      schema_type,
      nullable: false,
      editable: false,
      label: name,
      relation: None,
    }
  }

  /// Whether the field admits NULL.
  #[must_use]
  pub const fn nullable(mut self, nullable: bool) -> Self {
    self.nullable = nullable;
    self
  }

  /// Whether a generic form may bind the field.
  #[must_use]
  pub const fn editable(mut self, editable: bool) -> Self {
    self.editable = editable;
    self
  }

  /// The label key.
  #[must_use]
  pub const fn label(mut self, label: &'static str) -> Self {
    self.label = label;
    self
  }

  /// The `belongs_to` relation the field is the foreign key of.
  #[must_use]
  pub const fn relation(mut self, relation: &'static str) -> Self {
    self.relation = Some(relation);
    self
  }
}

/// The shape of a [`Relation`]: which keys join the parent `P` to the child `C`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum RelationKind {
  /// N:1 — `P.foreign_key` holds the child's primary key.
  BelongsTo {
    /// The column of `P` referencing `C`'s primary key.
    foreign_key: &'static str,
  },
  /// 1:N — `C.foreign_key` holds the parent's primary key.
  HasMany {
    /// The column of `C` referencing `P`'s primary key.
    foreign_key: &'static str,
  },
  /// N:M — rows of the join table `through` pair `local_key` (`P`'s primary key) with
  /// `foreign_key` (`C`'s primary key).
  ManyToMany {
    /// The join table.
    through: &'static str,
    /// The join-table column referencing `P`'s primary key.
    local_key: &'static str,
    /// The join-table column referencing `C`'s primary key.
    foreign_key: &'static str,
  },
}

/// One declared relation of an entity: [`Entity::RELATIONS`] (what [`Relation::meta`] returns).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct RelationMeta {
  /// The relation's name (the generated `Parent::name()` constructor).
  pub name: &'static str,
  /// Its keys.
  pub kind: RelationKind,
  /// The child entity's [`Entity::NAME`].
  pub target: &'static str,
  /// The child entity's [`Entity::TABLE`].
  pub target_table: &'static str,
}

impl RelationMeta {
  /// The relation `name` of `kind` to the entity `target` stored in `target_table`.
  pub const fn new(
    name: &'static str,
    kind: RelationKind,
    target: &'static str,
    target_table: &'static str,
  ) -> Self {
    Self {
      name,
      kind,
      target,
      target_table,
    }
  }
}

// ---- relations ----

/// A relation from the entity `P` to the entity `C`, to eager-load with [`Repository::with`]
/// and read back with [`Loaded::get`] (see the [module docs](self)).
///
/// `#[derive(Entity)]` generates one constructor per declared relation (`Order::lines()`);
/// [`belongs_to`](Self::belongs_to), [`has_many`](Self::has_many) and
/// [`many_to_many`](Self::many_to_many) build one by hand. [`with`](Self::with) nests the
/// relations of `C`.
///
/// ```rust
/// use id_effect_sql::repository::{Relation, RelationKind};
/// use id_effect_sql::{Entity, FromRow};
///
/// #[derive(Clone, Debug, FromRow, Entity)]
/// #[entity(table = "orders", has_many(Line, foreign_key = "order_id", name = "lines"))]
/// struct Order {
///   #[entity(id)]
///   id: i64,
/// }
///
/// #[derive(Clone, Debug, FromRow, Entity)]
/// #[entity(table = "lines")]
/// struct Line {
///   #[entity(id)]
///   id: i64,
///   order_id: i64,
/// }
///
/// let lines: Relation<Order, Line> = Order::lines();
/// assert_eq!(lines.kind(), RelationKind::HasMany { foreign_key: "order_id" });
/// assert_eq!(Order::RELATIONS, [lines.meta()]);
/// ```
pub struct Relation<P, C> {
  name: &'static str,
  kind: RelationKind,
  nested: Vec<Arc<dyn Loader<C>>>,
  entities: PhantomData<fn() -> (P, C)>,
}

impl<P, C> Clone for Relation<P, C> {
  fn clone(&self) -> Self {
    Self {
      name: self.name,
      kind: self.kind,
      nested: self.nested.clone(),
      entities: PhantomData,
    }
  }
}

impl<P, C> fmt::Debug for Relation<P, C> {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.debug_struct("Relation")
      .field("name", &self.name)
      .field("kind", &self.kind)
      .field("nested", &self.relations())
      .finish()
  }
}

impl<P, C> Relation<P, C> {
  fn new(name: &'static str, kind: RelationKind) -> Self {
    Self {
      name,
      kind,
      nested: Vec::new(),
      entities: PhantomData,
    }
  }

  /// N:1: the `C` whose primary key is `P`'s `foreign_key` column (a field of `P`; NULL loads
  /// nothing).
  pub fn belongs_to(name: &'static str, foreign_key: &'static str) -> Self {
    Self::new(name, RelationKind::BelongsTo { foreign_key })
  }

  /// 1:N: the `C`s whose `foreign_key` column holds `P`'s primary key.
  pub fn has_many(name: &'static str, foreign_key: &'static str) -> Self {
    Self::new(name, RelationKind::HasMany { foreign_key })
  }

  /// N:M: the `C`s paired with `P` in the join table `through` (`local_key` references `P`'s
  /// primary key, `foreign_key` `C`'s).
  pub fn many_to_many(
    name: &'static str,
    through: &'static str,
    local_key: &'static str,
    foreign_key: &'static str,
  ) -> Self {
    Self::new(
      name,
      RelationKind::ManyToMany {
        through,
        local_key,
        foreign_key,
      },
    )
  }

  /// The relation's name.
  #[inline]
  pub fn name(&self) -> &'static str {
    self.name
  }

  /// The relation's keys.
  #[inline]
  pub fn kind(&self) -> RelationKind {
    self.kind
  }

  /// The names of the nested relations loaded with the children.
  pub fn relations(&self) -> Vec<&'static str> {
    self.nested.iter().map(|l| l.name()).collect()
  }

  /// The levels this relation loads: 1, plus its deepest nested relation.
  pub fn depth(&self) -> usize {
    1 + max_depth(&self.nested)
  }
}

impl<P, C: Entity> Relation<P, C> {
  /// This relation, also loading `rel` on each child (`Order::lines().with(Line::product())`).
  /// A nested relation of the same name replaces the earlier one.
  #[must_use]
  pub fn with<G: Entity + Clone + Sync>(mut self, rel: Relation<C, G>) -> Self {
    add_loader(&mut self.nested, rel);
    self
  }

  /// The relation as metadata (an [`Entity::RELATIONS`] entry).
  pub fn meta(&self) -> RelationMeta {
    RelationMeta::new(self.name, self.kind, C::NAME, C::TABLE)
  }
}

/// A relation loader for the parent type `P`, type-erased over the child type.
trait Loader<P>: Send + Sync {
  fn name(&self) -> &'static str;
  fn depth(&self) -> usize;
  /// Whether the children (and theirs) can be scoped by `repo`'s tenant and filters: checked
  /// before the parent query, so a failing relation reads nothing.
  fn check(&self, repo: &Repository<P>) -> Result<(), SqlError>;
  /// Load the relation for `parents` (read through `repo`'s scoping) and attach it.
  fn load(
    &self,
    ex: Arc<dyn SqlExecutor>,
    repo: &Repository<P>,
    parents: Vec<Loaded<P>>,
  ) -> Effect<Vec<Loaded<P>>, SqlError>;
}

fn max_depth<P>(loaders: &[Arc<dyn Loader<P>>]) -> usize {
  loaders.iter().map(|l| l.depth()).max().unwrap_or(0)
}

fn add_loader<P: Entity, C: Entity + Clone + Sync>(
  loaders: &mut Vec<Arc<dyn Loader<P>>>,
  rel: Relation<P, C>,
) {
  loaders.retain(|l| l.name() != rel.name);
  loaders.push(Arc::new(rel));
}

/// A key value, comparable across the integer widths and text encodings drivers return.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
struct Key(String);

impl Key {
  fn of(value: &SqlValue) -> Self {
    Self(value.render())
  }
}

impl<P: Entity, C: Entity + Clone + Sync> Relation<P, C> {
  /// The key of `parent` this relation matches children on (`None`: a NULL foreign key).
  fn parent_key(&self, parent: &P) -> Result<Option<SqlValue>, SqlError> {
    let RelationKind::BelongsTo { foreign_key } = self.kind else {
      return Ok(Some(parent.id().to_sql_value()));
    };
    match parent
      .values()
      .into_iter()
      .find(|(col, _)| *col == foreign_key)
    {
      Some((_, SqlValue::Null)) => Ok(None),
      Some((_, value)) => Ok(Some(value)),
      None => Err(SqlError::Unsupported(format!(
        "relation `{}`: entity `{}` has no column `{foreign_key}` (the belongs_to foreign key \
         must be a field)",
        self.name,
        P::NAME
      ))),
    }
  }

  /// The children of the parents with keys `values`, each row with its owner key as [`KEY`].
  fn statement(&self, child: &Repository<C>, values: &[SqlValue]) -> Result<Stmt, SqlError> {
    let keys = || values.iter().cloned().map(Value::from);
    let mut stmt = Query::select();
    let key = match self.kind {
      RelationKind::ManyToMany {
        through,
        local_key,
        foreign_key,
      } => {
        let cond = Condition::all().add(Expr::col((through, local_key)).is_in(keys()));
        stmt
          .columns(C::COLUMNS.iter().map(|col| (C::TABLE, *col)))
          .expr_as(Expr::col((through, local_key)), KEY)
          .from(C::TABLE)
          .inner_join(
            through,
            Expr::col((through, foreign_key)).equals((C::TABLE, C::ID)),
          )
          .cond_where(and(child.scope_in(Some(C::TABLE), true)?, cond))
          .order_by((C::TABLE, C::ID), Order::Asc);
        return child.render(&stmt);
      }
      RelationKind::HasMany { foreign_key } => foreign_key,
      RelationKind::BelongsTo { .. } => C::ID,
    };
    stmt
      .columns(C::COLUMNS.iter().copied())
      .expr_as(Expr::col(key), KEY)
      .from(C::TABLE);
    child.filter(
      &mut stmt,
      Condition::all().add(Expr::col(key).is_in(keys())),
    )?;
    stmt.order_by(C::ID, Order::Asc);
    child.render(&stmt)
  }

  /// The parents' keys (in parent order) and the statements loading their children.
  fn prepare(
    &self,
    child: &Repository<C>,
    parents: &[Loaded<P>],
  ) -> Result<(Vec<Option<Key>>, VecDeque<Stmt>), SqlError> {
    // Fail closed on a scoping error even when there is nothing to load.
    child.scope(true)?;
    let mut keys = Vec::with_capacity(parents.len());
    let (mut values, mut seen) = (Vec::new(), HashSet::new());
    for parent in parents {
      let key = self.parent_key(&parent.entity)?.map(|value| {
        let key = Key::of(&value);
        if seen.insert(key.clone()) {
          values.push(value);
        }
        key
      });
      keys.push(key);
    }
    let stmts = values
      .chunks(IN_CHUNK)
      .map(|chunk| self.statement(child, chunk))
      .collect::<Result<_, _>>()?;
    Ok((keys, stmts))
  }
}

impl<P: Entity, C: Entity + Clone + Sync> Loader<P> for Relation<P, C> {
  fn name(&self) -> &'static str {
    self.name
  }

  fn depth(&self) -> usize {
    Relation::depth(self)
  }

  fn check(&self, repo: &Repository<P>) -> Result<(), SqlError> {
    let child = repo.cast::<C>();
    child.scope(true)?;
    self.nested.iter().try_for_each(|l| l.check(&child))
  }

  fn load(
    &self,
    ex: Arc<dyn SqlExecutor>,
    repo: &Repository<P>,
    parents: Vec<Loaded<P>>,
  ) -> Effect<Vec<Loaded<P>>, SqlError> {
    let child = repo.cast::<C>();
    let (keys, stmts) = match self.prepare(&child, &parents) {
      Ok(prepared) => prepared,
      Err(e) => return id_effect::fail(e),
    };
    let (name, nested) = (self.name, self.nested.clone());
    query_all(Arc::clone(&ex), stmts, Vec::new()).flat_map(move |rows| {
      let (owners, children): (Vec<Key>, Vec<Loaded<C>>) = match decode::<C>(&rows) {
        Ok(decoded) => decoded.into_iter().unzip(),
        Err(e) => return id_effect::fail(e),
      };
      load_all(ex, child, children, nested.into())
        .map(move |children| attach(name, parents, &keys, owners, children))
    })
  }
}

/// Run `stmts` one after the other, concatenating their rows.
fn query_all(
  ex: Arc<dyn SqlExecutor>,
  mut stmts: VecDeque<Stmt>,
  mut acc: Vec<SqlRow>,
) -> Effect<Vec<SqlRow>, SqlError> {
  let Some((sql, params)) = stmts.pop_front() else {
    return succeed(acc);
  };
  ex.query(&sql, &params).flat_map(move |rows| {
    acc.extend(rows);
    query_all(ex, stmts, acc)
  })
}

/// Each row's owner key and child.
fn decode<C: FromRow>(rows: &[SqlRow]) -> Result<Vec<(Key, Loaded<C>)>, SqlError> {
  rows
    .iter()
    .map(|row| Ok((Key::of(row.value(KEY)?), Loaded::new(C::from_row(row)?))))
    .collect()
}

/// Load `loaders` one after the other onto `parents`.
fn load_all<P: Entity>(
  ex: Arc<dyn SqlExecutor>,
  repo: Repository<P>,
  parents: Vec<Loaded<P>>,
  mut loaders: VecDeque<Arc<dyn Loader<P>>>,
) -> Effect<Vec<Loaded<P>>, SqlError> {
  let Some(loader) = loaders.pop_front() else {
    return succeed(parents);
  };
  loader
    .load(Arc::clone(&ex), &repo, parents)
    .flat_map(move |parents| load_all(ex, repo, parents, loaders))
}

/// Give each parent the children whose owner key is its key (cloned only when parents share
/// them).
fn attach<P, C: Clone + Send + Sync + 'static>(
  name: &'static str,
  parents: Vec<Loaded<P>>,
  keys: &[Option<Key>],
  owners: Vec<Key>,
  children: Vec<Loaded<C>>,
) -> Vec<Loaded<P>> {
  let mut groups: HashMap<Key, Vec<Loaded<C>>> = HashMap::new();
  for (owner, child) in owners.into_iter().zip(children) {
    groups.entry(owner).or_default().push(child);
  }
  let mut uses: HashMap<&Key, usize> = HashMap::new();
  for key in keys.iter().flatten() {
    *uses.entry(key).or_default() += 1;
  }
  parents
    .into_iter()
    .zip(keys)
    .map(|(mut parent, key)| {
      let children = match key {
        None => Vec::new(),
        Some(key) => match uses.get_mut(key) {
          Some(left) if *left > 1 => {
            *left -= 1;
            groups.get(key).cloned().unwrap_or_default()
          }
          _ => groups.remove(key).unwrap_or_default(),
        },
      };
      parent.slots.push(Slot {
        name,
        children: Arc::new(children),
      });
      parent
    })
    .collect()
}

