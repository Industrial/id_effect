/// A loaded relation: its name and the `Vec<Loaded<C>>` of one parent.
#[derive(Clone)]
struct Slot {
  name: &'static str,
  children: Arc<dyn Any + Send + Sync>,
}

/// An entity with its eager-loaded relations ([`Repository::with`]). Derefs to the entity;
/// [`get`](Self::get) reads a relation.
///
/// ```rust
/// use id_effect_sql::repository::{Loaded, Relation};
///
/// # #[derive(Clone, Debug, PartialEq)] struct Order { id: i64 }
/// # #[derive(Clone, Debug, PartialEq)] struct Line { id: i64 }
/// let order = Loaded::new(Order { id: 1 });
/// let lines = Relation::<Order, Line>::has_many("lines", "order_id");
/// assert_eq!(order.id, 1);
/// assert!(order.get(&lines).is_empty());
/// assert!(order.try_get(&lines).is_none(), "not loaded");
/// ```
pub struct Loaded<T> {
  entity: T,
  slots: Vec<Slot>,
}

impl<T> Loaded<T> {
  /// `entity` with no relation loaded.
  pub fn new(entity: T) -> Self {
    Self {
      entity,
      slots: Vec::new(),
    }
  }

  /// The entity.
  #[inline]
  pub fn entity(&self) -> &T {
    &self.entity
  }

  /// The entity, without its relations.
  #[inline]
  pub fn into_entity(self) -> T {
    self.entity
  }

  /// The children `rel` loaded (empty when it found none, or was not loaded). For a
  /// `belongs_to` relation, at most one: see [`one`](Self::one).
  pub fn get<C: 'static>(&self, rel: &Relation<T, C>) -> &[Loaded<C>] {
    self.try_get(rel).unwrap_or(&[])
  }

  /// The children `rel` loaded, or `None` when it was not loaded.
  pub fn try_get<C: 'static>(&self, rel: &Relation<T, C>) -> Option<&[Loaded<C>]> {
    self
      .slots
      .iter()
      .filter(|slot| slot.name == rel.name)
      .find_map(|slot| slot.children.downcast_ref::<Vec<Loaded<C>>>())
      .map(Vec::as_slice)
  }

  /// The first child `rel` loaded: the parent of a `belongs_to` relation.
  pub fn one<C: 'static>(&self, rel: &Relation<T, C>) -> Option<&Loaded<C>> {
    self.get(rel).first()
  }

  /// The names of the loaded relations.
  pub fn relations(&self) -> Vec<&'static str> {
    self.slots.iter().map(|slot| slot.name).collect()
  }
}

impl<T> Deref for Loaded<T> {
  type Target = T;

  fn deref(&self) -> &T {
    &self.entity
  }
}

impl<T: Clone> Clone for Loaded<T> {
  fn clone(&self) -> Self {
    Self {
      entity: self.entity.clone(),
      slots: self.slots.clone(),
    }
  }
}

impl<T: fmt::Debug> fmt::Debug for Loaded<T> {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.debug_struct("Loaded")
      .field("entity", &self.entity)
      .field("relations", &self.relations())
      .finish()
  }
}

