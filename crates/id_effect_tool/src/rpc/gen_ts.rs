/// ASCII letters, digits and `_`; everything else becomes `_` (as `openapi`'s rule).
fn ident(text: &str) -> String {
  let out: String = text
    .chars()
    .map(|c| {
      if c.is_ascii_alphanumeric() || c == '_' {
        c
      } else {
        '_'
      }
    })
    .collect();
  if out.is_empty() { "_".to_owned() } else { out }
}

/// A TypeScript identifier for `text`: [`ident`], `_` in front of a leading digit.
fn ts_ident(text: &str) -> String {
  let out = ident(text);
  if out.starts_with(|c: char| c.is_ascii_digit()) {
    format!("_{out}")
  } else {
    out
  }
}

/// `all_titles` → `AllTitles`, `todos` → `Todos`.
fn pascal(text: &str) -> String {
  let mut out = String::new();
  for part in text.split(|c: char| !c.is_ascii_alphanumeric()) {
    let mut chars = part.chars();
    if let Some(first) = chars.next() {
      out.push(first.to_ascii_uppercase());
      out.extend(chars);
    }
  }
  if out.is_empty() {
    "_".to_owned()
  } else if out.starts_with(|c: char| c.is_ascii_digit()) {
    format!("_{out}")
  } else {
    out
  }
}

fn key_segments(key: &str) -> Vec<String> {
  let segs: Vec<String> = key
    .split("::")
    .map(|seg| ident(seg).trim_end_matches('_').to_owned())
    .filter(|seg| !seg.is_empty())
    .collect();
  if segs.is_empty() {
    vec!["Schema".to_owned()]
  } else {
    segs
  }
}

/// Base names of definition keys: the last `::` segment, or the shortest suffix no other key
/// shares (`openapi`'s rule, joined with `.` there).
fn def_names(keys: &[&str]) -> BTreeMap<String, String> {
  let segments: Vec<Vec<String>> = keys.iter().map(|k| key_segments(k)).collect();
  let suffix = |segs: &[String], n: usize| segs[segs.len().saturating_sub(n)..].join(".");
  let mut out = BTreeMap::new();
  for (i, segs) in segments.iter().enumerate() {
    let name = (1..=segs.len())
      .map(|n| (n, suffix(segs, n)))
      .find(|(n, candidate)| {
        !segments
          .iter()
          .enumerate()
          .any(|(j, other)| j != i && other.len() >= *n && suffix(other, *n) == *candidate)
      })
      .map_or_else(|| suffix(segs, segs.len()), |(_, name)| name);
    out.insert(keys[i].to_owned(), name);
  }
  out
}

/// `value` as JSON text with every object's keys sorted.
fn text_of(value: &Value) -> String {
  fn canonical(value: &Value) -> Value {
    match value {
      Value::Object(map) => {
        let sorted: BTreeMap<&String, Value> = map.iter().map(|(k, v)| (k, canonical(v))).collect();
        Value::Object(sorted.into_iter().map(|(k, v)| (k.clone(), v)).collect())
      }
      Value::Array(items) => Value::Array(items.iter().map(canonical).collect()),
      other => other.clone(),
    }
  }
  serde_json::to_string(&canonical(value)).unwrap_or_default()
}

/// The `$defs` of `root`, sorted by key.
fn defs_of(root: &Value) -> Vec<(&String, &Value)> {
  let mut list: Vec<_> = root
    .get("$defs")
    .and_then(Value::as_object)
    .map(|defs| defs.iter().collect())
    .unwrap_or_default();
  list.sort_by(|a, b| a.0.cmp(b.0));
  list
}

fn roots_of(procedure: &ProcedureContract) -> impl Iterator<Item = &Value> {
  [
    Some(&procedure.input),
    Some(&procedure.output),
    procedure.error.as_ref(),
  ]
  .into_iter()
  .flatten()
}

/// One definition: its TypeScript name, body and the root its references resolve in.
struct Def {
  name: String,
  body: Value,
  root: Value,
}

#[derive(Default)]
struct Plan {
  /// (key, body text) → definition.
  defs: BTreeMap<(String, String), Def>,
  taken: BTreeSet<String>,
  /// (service index, procedure name) → alias base (`TodosV1Get`).
  aliases: BTreeMap<(usize, String), String>,
  /// (service index) → class name.
  classes: BTreeMap<usize, String>,
}

impl Plan {
  /// A name nothing else has: `base`, else `base_`, `base__`, ….
  fn claim(&mut self, base: &str) -> String {
    let mut name = base.to_owned();
    while self.taken.contains(&name) || KEYWORDS.contains(&name.as_str()) {
      name.push('_');
    }
    self.taken.insert(name.clone());
    name
  }

  fn check(&mut self, services: &[&ServiceContract]) -> Result<(), GenTsError> {
    let mut classes = BTreeSet::new();
    for (i, service) in services.iter().enumerate() {
      let class = format!("{}V{}Client", pascal(&service.name), service.version);
      if !classes.insert(class.clone()) {
        return Err(GenTsError::Invalid(format!(
          "two services become the class `{class}`"
        )));
      }
      self.classes.insert(i, class);
      let mut methods = BTreeSet::new();
      for procedure in &service.procedures {
        let tag = format!("{}.{}", service.name, procedure.name);
        if !id_effect_rpc::registry::is_valid_tag(&tag) {
          return Err(GenTsError::Invalid(format!(
            "`{tag}` is not a procedure tag"
          )));
        }
        if !methods.insert(method_name(&procedure.name)) {
          return Err(GenTsError::Invalid(format!(
            "two procedures of {} v{} become the method `{}`",
            service.name,
            service.version,
            method_name(&procedure.name)
          )));
        }
      }
    }
    Ok(())
  }

  fn name_defs(&mut self, services: &[&ServiceContract]) {
    let mut found: BTreeMap<(String, String), (Value, Value)> = BTreeMap::new();
    for service in services {
      for procedure in &service.procedures {
        for root in roots_of(procedure) {
          for (key, body) in defs_of(root) {
            found
              .entry((key.clone(), text_of(body)))
              .or_insert_with(|| (body.clone(), root.clone()));
          }
        }
      }
    }
    let keys: Vec<&str> = found
      .keys()
      .map(|(k, _)| k.as_str())
      .collect::<BTreeSet<_>>()
      .into_iter()
      .collect();
    let bases = def_names(&keys);
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut named = Vec::new();
    for (key, text) in found.keys() {
      let base = bases[key.as_str()].replace('.', "_");
      let n = seen.entry(base.clone()).or_insert(0);
      *n += 1;
      let base = if *n == 1 { base } else { format!("{base}_{n}") };
      named.push(((key.clone(), text.clone()), ts_ident(&base)));
    }
    for (pair, base) in named {
      let name = self.claim(&base);
      let (body, root) = found.remove(&pair).unwrap_or_default();
      self.defs.insert(pair, Def { name, body, root });
    }
    for (i, service) in services.iter().enumerate() {
      for procedure in &service.procedures {
        let base = format!(
          "{}V{}{}",
          pascal(&service.name),
          service.version,
          pascal(&procedure.name)
        );
        let mut base = base;
        while ["Input", "Output", "Error"]
          .iter()
          .any(|s| self.taken.contains(&format!("{base}{s}")))
        {
          base.push('_');
        }
        for s in ["Input", "Output", "Error"] {
          self.taken.insert(format!("{base}{s}"));
        }
        self.aliases.insert((i, procedure.name.clone()), base);
      }
    }
  }

  /// `#/$defs/<token>` → TypeScript name, for `root`'s definitions.
  fn tokens(&self, root: &Value) -> BTreeMap<String, String> {
    defs_of(root)
      .into_iter()
      .filter_map(|(key, body)| {
        let def = self.defs.get(&(key.clone(), text_of(body)))?;
        let token = key.replace('~', "~0").replace('/', "~1");
        Some((token, def.name.clone()))
      })
      .collect()
  }

  fn types(&self, services: &[&ServiceContract]) -> String {
    let mut out = String::from(HEADER);
    out.push_str("//\n// The types of the contract's services.\n");
    if !self.defs.is_empty() {
      out.push_str("\n// Definitions (`$defs`).\n");
    }
    let mut defs: Vec<&Def> = self.defs.values().collect();
    defs.sort_by(|a, b| a.name.cmp(&b.name));
    for def in defs {
      out.push('\n');
      let tokens = self.tokens(&def.root);
      let types = Types { tokens: &tokens };
      if let Some(format) = date_format(&def.body) {
        push_doc(&mut out, "", &format!("An ISO 8601 {format} string."));
        out.push_str(&format!("export type {} = string;\n", def.name));
        continue;
      }
      if let Some(description) = def.body.get("description").and_then(Value::as_str) {
        push_doc(&mut out, "", description);
      }
      let body = match brand_base(&def.body) {
        Some(base) => format!(" {base} & {{ readonly __brand: {} }}", literal(&def.name)),
        None => types.alias(&def.body),
      };
      out.push_str(&format!("export type {} ={body};\n", def.name));
    }
    for (i, service) in services.iter().enumerate() {
      out.push_str(&format!(
        "\n// {} version {}.\n",
        service.name, service.version
      ));
      for procedure in &service.procedures {
        let base = &self.aliases[&(i, procedure.name.clone())];
        let tag = format!("{}.{}", service.name, procedure.name);
        let (input_doc, output_doc) = match procedure.kind {
          ProcedureKind::Query | ProcedureKind::Mutation => ("input", "output"),
          ProcedureKind::ServerStream | ProcedureKind::Subscription => ("input", "output item"),
          ProcedureKind::ClientStream => ("input item", "output"),
          ProcedureKind::Bidi => ("input item", "output item"),
        };
        let parts = [
          ("Input", input_doc, Some(&procedure.input)),
          ("Output", output_doc, Some(&procedure.output)),
          ("Error", "typed error union", procedure.error.as_ref()),
        ];
        for (suffix, what, schema) in parts {
          out.push('\n');
          let mut doc = format!("The {what} of `{tag}`.");
          if let Some(d) = schema
            .and_then(|s| s.get("description"))
            .and_then(Value::as_str)
          {
            doc = format!("{doc}\n\n{d}");
          }
          push_doc(&mut out, "", &doc);
          let body = match schema {
            Some(schema) => {
              let tokens = self.tokens(schema);
              Types { tokens: &tokens }.alias(schema)
            }
            None => " never".to_owned(),
          };
          out.push_str(&format!("export type {base}{suffix} ={body};\n"));
        }
      }
    }
    out
  }

  fn client(&self, services: &[&ServiceContract]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(
      "//\n// One client class per service and version; they share an `RpcConnection`.\n\n",
    );
    out.push_str("import { RpcConnection } from \"./runtime.ts\";\n");
    out.push_str("import type {\n  CallOptions,\n  RpcClientOptions,\n  RpcDuplex,\n  RpcResult,\n  RpcStream,\n  SubscribeOptions,\n} from \"./runtime.ts\";\n");
    out.push_str("import type * as T from \"./types.ts\";\n\n");
    out.push_str("export * from \"./runtime.ts\";\n");
    for (i, service) in services.iter().enumerate() {
      out.push('\n');
      let class = &self.classes[&i];
      let title = format!("`{}` version {}.", service.name, service.version);
      let doc = match &service.description {
        Some(d) => format!("{d}\n\n{title}"),
        None => title,
      };
      push_doc(&mut out, "", &doc);
      out.push_str(&format!("export class {class} {{\n"));
      out.push_str(&format!(
        "  /** The service name. */\n  static readonly service = {};\n",
        literal(&service.name)
      ));
      out.push_str(&format!(
        "  /** The service version. */\n  static readonly version = {};\n",
        service.version
      ));
      out.push_str("  /** The connection the calls go over (share it between clients). */\n  readonly connection: RpcConnection;\n\n");
      out.push_str("  constructor(connection: RpcConnection | RpcClientOptions) {\n    this.connection = connection instanceof RpcConnection ? connection : new RpcConnection(connection);\n  }\n");
      for procedure in &service.procedures {
        out.push('\n');
        let base = &self.aliases[&(i, procedure.name.clone())];
        out.push_str(&method(service, procedure, base));
      }
      out.push_str("}\n");
    }
    out
  }
}

fn method_name(name: &str) -> String {
  let name = ts_ident(name);
  if matches!(name.as_str(), "connection" | "constructor") {
    format!("{name}_")
  } else {
    name
  }
}

fn method(service: &ServiceContract, procedure: &ProcedureContract, base: &str) -> String {
  let tag = literal(&format!("{}.{}", service.name, procedure.name));
  let v = service.version;
  let name = method_name(&procedure.name);
  let mut doc = procedure.description.clone().unwrap_or_default();
  if !doc.is_empty() {
    doc.push_str("\n\n");
  }
  let access = match &procedure.access {
    ProcedureAccess::Public {} => "public".to_owned(),
    ProcedureAccess::Guarded { policies } => format!("guarded by {}", policies.join(", ")),
  };
  doc.push_str(&format!(
    "`{}` ({}, {access}",
    procedure.name, procedure.kind
  ));
  if procedure.idempotent {
    doc.push_str(", idempotent");
  }
  if let Some(n) = procedure.max_items {
    doc.push_str(&format!(", at most {n} items"));
  }
  if let Some(n) = procedure.max_bytes {
    doc.push_str(&format!(", at most {n} bytes"));
  }
  doc.push_str(").");
  if procedure.deprecated {
    doc.push_str("\n@deprecated");
  }
  let mut out = String::new();
  push_doc(&mut out, "  ", &doc);
  let (i, o, e) = (
    format!("T.{base}Input"),
    format!("T.{base}Output"),
    format!("T.{base}Error"),
  );
  let unit = is_null_schema(&procedure.input);
  let (params, input) = if unit {
    (String::new(), "null")
  } else {
    (format!("input: {i}, "), "input")
  };
  let body = match procedure.kind {
    ProcedureKind::Query | ProcedureKind::Mutation => format!(
      "{name}({params}options?: CallOptions): Promise<RpcResult<{o}, {e}>> {{\n    return this.connection.unary({tag}, {v}, \"{}\", {input}, options);\n  }}\n",
      procedure.kind
    ),
    ProcedureKind::ServerStream => format!(
      "{name}({params}options?: CallOptions): RpcStream<{o}, {e}> {{\n    return this.connection.serverStream({tag}, {v}, {input}, options);\n  }}\n"
    ),
    ProcedureKind::Subscription => format!(
      "{name}({params}options?: SubscribeOptions): RpcStream<{o}, {e}> {{\n    return this.connection.subscription({tag}, {v}, {input}, options);\n  }}\n"
    ),
    ProcedureKind::ClientStream => format!(
      "{name}(items: Iterable<{i}> | AsyncIterable<{i}>, options?: CallOptions): Promise<RpcResult<{o}, {e}>> {{\n    return this.connection.clientStream({tag}, {v}, items, options);\n  }}\n"
    ),
    ProcedureKind::Bidi => format!(
      "{name}(options?: CallOptions): RpcDuplex<{i}, {o}, {e}> {{\n    return this.connection.bidi({tag}, {v}, options);\n  }}\n"
    ),
  };
  out.push_str("  ");
  out.push_str(&body);
  out
}

/// A JSDoc comment of `text` at `indent`.
fn push_doc(out: &mut String, indent: &str, text: &str) {
  let text = text.replace("*/", "*\\/");
  let lines: Vec<&str> = text.lines().map(str::trim_end).collect();
  if lines.len() == 1 {
    out.push_str(&format!("{indent}/** {} */\n", lines[0]));
    return;
  }
  out.push_str(&format!("{indent}/**\n"));
  for line in lines {
    if line.is_empty() {
      out.push_str(&format!("{indent} *\n"));
    } else {
      out.push_str(&format!("{indent} * {line}\n"));
    }
  }
  out.push_str(&format!("{indent} */\n"));
}

/// A TypeScript string literal (JSON's escaping is valid TypeScript).
fn literal(text: &str) -> String {
  serde_json::to_string(text).unwrap_or_default()
}

fn is_null_schema(schema: &Value) -> bool {
  schema.get("type").and_then(Value::as_str) == Some("null")
}

const COMPOSITE: &[&str] = &[
  "$ref",
  "enum",
  "const",
  "anyOf",
  "oneOf",
  "allOf",
  "properties",
  "items",
  "prefixItems",
  "additionalProperties",
];

/// A scalar body: `string`, `integer`, `number` or `boolean` alone, with constraints only.
fn scalar_type(body: &Value) -> Option<&str> {
  let ty = body.get("type")?.as_str()?;
  if !matches!(ty, "string" | "integer" | "number" | "boolean") {
    return None;
  }
  let map = body.as_object()?;
  if COMPOSITE.iter().any(|k| map.contains_key(*k)) {
    return None;
  }
  Some(ty)
}

fn date_format(body: &Value) -> Option<&str> {
  if scalar_type(body)? != "string" {
    return None;
  }
  body
    .get("format")
    .and_then(Value::as_str)
    .filter(|f| matches!(*f, "date-time" | "date" | "time"))
}

fn brand_base(body: &Value) -> Option<&'static str> {
  match scalar_type(body)? {
    "string" => Some("string"),
    "boolean" => Some("boolean"),
    _ => Some("number"),
  }
}

// ---------------------------------------------------------------------------------------------
// JSON Schema → TypeScript
// ---------------------------------------------------------------------------------------------

struct Types<'a> {
  tokens: &'a BTreeMap<String, String>,
}

fn pad(indent: usize) -> String {
  " ".repeat(indent)
}

/// Whether a type needs parentheses in front of `[]`.
fn compound(ty: &str) -> bool {
  let mut depth = 0_i32;
  for c in ty.chars() {
    match c {
      '{' | '(' | '[' | '<' => depth += 1,
      '}' | ')' | ']' | '>' => depth -= 1,
      '|' | '&' if depth == 0 => return true,
      _ => {}
    }
  }
  false
}

impl Types<'_> {
  /// The right-hand side of `export type X =`: one line, or one union arm per line (`| …`)
  /// when an arm spans lines or the union is long.
  fn alias(&self, schema: &Value) -> String {
    let arms = self.arms(schema, 4);
    let long = arms.iter().any(|a| a.contains('\n')) || arms.join(" | ").len() > 80;
    if arms.len() > 1 && long {
      arms.iter().map(|a| format!("\n  | {a}")).collect()
    } else {
      format!(" {}", self.ty(schema, 0))
    }
  }

  /// The union arms of `schema` (one arm when it is no union), deduplicated.
  fn arms(&self, schema: &Value, indent: usize) -> Vec<String> {
    let arms: Vec<String> = match schema {
      Value::Object(map) if !map.contains_key("$ref") && !map.contains_key("const") => {
        if let Some(Value::Array(values)) = map.get("enum") {
          values.iter().map(const_type).collect()
        } else if let Some(Value::Array(arms)) = map.get("anyOf").or_else(|| map.get("oneOf")) {
          arms.iter().map(|arm| self.ty(arm, indent)).collect()
        } else {
          vec![self.ty(schema, indent)]
        }
      }
      _ => vec![self.ty(schema, indent)],
    };
    let mut seen = BTreeSet::new();
    arms
      .into_iter()
      .filter(|a| seen.insert(a.clone()))
      .collect()
  }

  /// The TypeScript type of `schema`, its continuation lines indented for a line at `indent`.
  fn ty(&self, schema: &Value, indent: usize) -> String {
    let map = match schema {
      Value::Bool(true) => return "unknown".to_owned(),
      Value::Bool(false) => return "never".to_owned(),
      Value::Object(map) => map,
      _ => return "unknown".to_owned(),
    };
    if let Some(reference) = map.get("$ref").and_then(Value::as_str) {
      return reference
        .strip_prefix("#/$defs/")
        .and_then(|token| self.tokens.get(token))
        .cloned()
        .unwrap_or_else(|| "unknown".to_owned());
    }
    if let Some(value) = map.get("const") {
      return const_type(value);
    }
    if let Some(Value::Array(values)) = map.get("enum") {
      return union(values.iter().map(const_type).collect());
    }
    for key in ["anyOf", "oneOf"] {
      if let Some(Value::Array(arms)) = map.get(key) {
        return union(arms.iter().map(|arm| self.ty(arm, indent)).collect());
      }
    }
    if let Some(Value::Array(parts)) = map.get("allOf") {
      let parts: Vec<String> = parts.iter().map(|p| self.ty(p, indent)).collect();
      return match parts.len() {
        0 => "unknown".to_owned(),
        _ => parts
          .iter()
          .map(|p| {
            if compound(p) {
              format!("({p})")
            } else {
              p.clone()
            }
          })
          .collect::<Vec<_>>()
          .join(" & "),
      };
    }
    match map.get("type") {
      Some(Value::String(ty)) => self.typed(ty, map, indent),
      Some(Value::Array(types)) => union(
        types
          .iter()
          .filter_map(Value::as_str)
          .map(|ty| self.typed(ty, map, indent))
          .collect(),
      ),
      _ if map.contains_key("properties") => self.typed("object", map, indent),
      _ => "unknown".to_owned(),
    }
  }

  fn typed(&self, ty: &str, map: &serde_json::Map<String, Value>, indent: usize) -> String {
    match ty {
      "string" => "string".to_owned(),
      "integer" | "number" => "number".to_owned(),
      "boolean" => "boolean".to_owned(),
      "null" => "null".to_owned(),
      "array" => self.array(map, indent),
      "object" => self.object(map, indent),
      _ => "unknown".to_owned(),
    }
  }

  fn array(&self, map: &serde_json::Map<String, Value>, indent: usize) -> String {
    if let Some(Value::Array(prefix)) = map.get("prefixItems") {
      let mut items: Vec<String> = prefix.iter().map(|p| self.ty(p, indent)).collect();
      match map.get("items") {
        Some(Value::Bool(false)) => {}
        None | Some(Value::Bool(true)) => items.push("...unknown[]".to_owned()),
        Some(rest) => {
          let rest = self.ty(rest, indent);
          let rest = if compound(&rest) {
            format!("({rest})")
          } else {
            rest
          };
          items.push(format!("...{rest}[]"));
        }
      }
      return format!("[{}]", items.join(", "));
    }
    let item = map
      .get("items")
      .map_or_else(|| "unknown".to_owned(), |items| self.ty(items, indent));
    if compound(&item) {
      format!("({item})[]")
    } else {
      format!("{item}[]")
    }
  }

  fn object(&self, map: &serde_json::Map<String, Value>, indent: usize) -> String {
    let required: BTreeSet<&str> = map
      .get("required")
      .and_then(Value::as_array)
      .map(|r| r.iter().filter_map(Value::as_str).collect())
      .unwrap_or_default();
    let properties: BTreeMap<&String, &Value> = map
      .get("properties")
      .and_then(Value::as_object)
      .map(|p| p.iter().collect())
      .unwrap_or_default();
    let additional = match map.get("additionalProperties") {
      None | Some(Value::Bool(true)) if properties.is_empty() => Some("unknown".to_owned()),
      None | Some(Value::Bool(true)) => None,
      Some(Value::Bool(false)) if properties.is_empty() => Some("never".to_owned()),
      Some(Value::Bool(false)) => None,
      Some(schema) => Some(self.ty(schema, indent)),
    };
    let index = additional.map(|value| format!("{{ [key: string]: {value} }}"));
    if properties.is_empty() {
      return index.unwrap_or_else(|| "{ [key: string]: unknown }".to_owned());
    }
    let inner = indent + 2;
    let mut out = String::from("{\n");
    for (name, schema) in properties {
      if let Some(description) = schema.get("description").and_then(Value::as_str) {
        push_doc(&mut out, &pad(inner), description);
      }
      let key = if is_identifier(name) {
        name.clone()
      } else {
        literal(name)
      };
      let optional = if required.contains(name.as_str()) {
        ""
      } else {
        "?"
      };
      out.push_str(&format!(
        "{}{key}{optional}: {};\n",
        pad(inner),
        self.ty(schema, inner)
      ));
    }
    out.push_str(&pad(indent));
    out.push('}');
    match index {
      Some(index) => format!("{out} & {index}"),
      None => out,
    }
  }
}

fn is_identifier(name: &str) -> bool {
  let mut chars = name.chars();
  chars
    .next()
    .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
    && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn const_type(value: &Value) -> String {
  match value {
    Value::String(s) => literal(s),
    Value::Number(n) => n.to_string(),
    Value::Bool(b) => b.to_string(),
    Value::Null => "null".to_owned(),
    _ => "unknown".to_owned(),
  }
}

/// `a | b | …` without repeats (`never` when empty).
fn union(arms: Vec<String>) -> String {
  let mut seen = BTreeSet::new();
  let arms: Vec<String> = arms
    .into_iter()
    .filter(|arm| seen.insert(arm.clone()))
    .collect();
  if arms.is_empty() {
    return "never".to_owned();
  }
  arms.join(" | ")
}

