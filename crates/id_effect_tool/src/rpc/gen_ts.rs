//! `id-effect rpc gen ts`: a typed TypeScript client from a service contract (ADR 0014 D11, D12).
//!
//! [`generate`] turns a [`Contract`] (`rpc.contract.json`, or `XService::contract()`) into three
//! files of plain TypeScript with no dependency:
//!
//! | File | Holds |
//! |---|---|
//! | `types.ts` | the contract's types: every `$defs` entry, and per procedure `<Service>V<N><Proc>Input` / `Output` / `Error` |
//! | `client.ts` | one class per service and version, `<Service>V<N>Client`, with one method per procedure; re-exports `runtime.ts` |
//! | `runtime.ts` | the runtime the classes share ([`RUNTIME_TS`]): batching, transports, frames, resume |
//!
//! Types from JSON Schema 2020-12: objects become object types (a property outside `required` is
//! optional, `anyOf [T, null]` is `T | null`), arrays `T[]`, `prefixItems` tuples,
//! `additionalProperties` maps `{ [key: string]: V }`, `anyOf` / `oneOf` unions (error unions are
//! discriminated on `_tag`), `const` / `enum` literal types, `allOf` intersections, `integer` and
//! `number` `number`, anything else `unknown`. A definition whose body is a scalar with a date
//! `format` (`date-time`, `date`, `time`) is an ISO 8601 `string`; any other scalar definition (a
//! newtype) is a branded type, `string & { readonly __brand: "OrderId" }`.
//!
//! Definitions are named as in [`id_effect_rpc::openapi`]: after the last `::` segment of the
//! `$defs` key, two keys sharing it both taking the shortest `::` suffix no other key shares
//! (joined with `_` instead of `.`), the same key with different bodies numbered `_2`, `_3`, … in
//! the order of their JSON text. A name that is a TypeScript keyword, or taken by an earlier name,
//! gets a trailing `_`.
//!
//! Output is deterministic: services by `(name, version)`, procedures by name, object members by
//! name, and nothing that depends on the time or the tool's version. Each file starts with
//! `// biome-ignore-all format` and `// deno-fmt-ignore-file`, so formatters leave it as generated.
//!
//! ```rust
//! use id_effect_rpc::contract::{Contract, ProcedureAccess, ProcedureContract, ProcedureKind, ServiceContract};
//! use id_effect_tool::rpc::gen_ts::generate;
//! use serde_json::json;
//!
//! let greet = ProcedureContract::new("greet", ProcedureKind::Query, ProcedureAccess::Public {},
//!   json!({"type": "string"}), json!({"type": "string"}));
//! let contract = Contract::new().with_service(ServiceContract::new("Greeter", 1).with_procedure(greet));
//! let files = generate(&contract).unwrap();
//! let client = files.iter().find(|f| f.path == "client.ts").unwrap();
//! assert!(client.contents.contains("export class GreeterV1Client {"));
//! assert!(client.contents.contains(r#"this.connection.unary("Greeter.greet", 1, "query", input, options)"#));
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::{Path, PathBuf};

use id_effect_rpc::contract::{
  Contract, ContractError, ProcedureAccess, ProcedureContract, ProcedureKind, ServiceContract,
};
use serde_json::Value;

/// The runtime every generated client shares (written as `runtime.ts`).
pub const RUNTIME_TS: &str = include_str!("ts/runtime.ts");

/// The files [`generate`] writes, in order.
pub const FILES: [&str; 3] = ["client.ts", "runtime.ts", "types.ts"];

const HEADER: &str = "// biome-ignore-all format: generated by id-effect rpc gen ts\n\
// deno-fmt-ignore-file\n\
// Generated by `id-effect rpc gen ts` (crate id_effect_tool). Do not edit: rerun the generator.\n";

/// One generated file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TsFile {
  /// The file name inside the output directory.
  pub path: &'static str,
  /// Its contents.
  pub contents: String,
}

/// Why no client was generated.
#[derive(Debug)]
#[non_exhaustive]
pub enum GenTsError {
  /// The contract file could not be read.
  Read {
    /// The contract file.
    path: PathBuf,
    /// Why.
    source: std::io::Error,
  },
  /// The contract is not a contract document.
  Contract(ContractError),
  /// The contract cannot become TypeScript (a malformed tag, two procedures with one method
  /// name, two services with one class name).
  Invalid(String),
  /// An output file could not be written.
  Write {
    /// The file.
    path: PathBuf,
    /// Why.
    source: std::io::Error,
  },
}

impl fmt::Display for GenTsError {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    match self {
      Self::Read { path, source } => write!(f, "cannot read {}: {source}", path.display()),
      Self::Contract(e) => write!(f, "{e}"),
      Self::Invalid(why) => write!(f, "cannot generate TypeScript: {why}"),
      Self::Write { path, source } => write!(f, "cannot write {}: {source}", path.display()),
    }
  }
}

impl std::error::Error for GenTsError {
  fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
    match self {
      Self::Read { source, .. } | Self::Write { source, .. } => Some(source),
      Self::Contract(e) => Some(e),
      Self::Invalid(_) => None,
    }
  }
}

/// Read the contract at `contract`, generate the client and write [`FILES`] into `out` (created
/// when missing; other files there are left alone). Returns the paths written.
pub fn generate_to(contract: &Path, out: &Path) -> Result<Vec<PathBuf>, GenTsError> {
  let text = std::fs::read_to_string(contract).map_err(|source| GenTsError::Read {
    path: contract.to_path_buf(),
    source,
  })?;
  let contract = Contract::from_json(&text).map_err(GenTsError::Contract)?;
  let files = generate(&contract)?;
  std::fs::create_dir_all(out).map_err(|source| GenTsError::Write {
    path: out.to_path_buf(),
    source,
  })?;
  let mut written = Vec::new();
  for file in files {
    let path = out.join(file.path);
    std::fs::write(&path, file.contents).map_err(|source| GenTsError::Write {
      path: path.clone(),
      source,
    })?;
    written.push(path);
  }
  Ok(written)
}

/// Generate the client of `contract`: [`FILES`], in that order.
pub fn generate(contract: &Contract) -> Result<Vec<TsFile>, GenTsError> {
  let mut services: Vec<&ServiceContract> = contract.services.iter().collect();
  services.sort_by(|a, b| (&a.name, a.version).cmp(&(&b.name, b.version)));
  let mut plan = Plan::default();
  plan.check(&services)?;
  plan.name_defs(&services);
  // No newline after the last line: what Biome leaves of a `biome-ignore-all` file, so a
  // formatter run over the output changes nothing.
  let types = plan.types(&services).trim_end().to_owned();
  let client = plan.client(&services).trim_end().to_owned();
  Ok(vec![
    TsFile {
      path: "client.ts",
      contents: client,
    },
    TsFile {
      path: "runtime.ts",
      contents: RUNTIME_TS.trim_end().to_owned(),
    },
    TsFile {
      path: "types.ts",
      contents: types,
    },
  ])
}

