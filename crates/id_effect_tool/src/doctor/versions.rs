//! `versions`: every id_effect crate in `Cargo.lock` resolves to one version. Two versions put
//! two copies of a crate in the build, and their types (`Effect`, `Layer`, capabilities) do not
//! unify across copies.

use std::collections::BTreeSet;
use std::fs;
use std::path::PathBuf;

use super::Check;
use super::project::{Project, toml_entries, unquote};

const NAME: &str = "versions";

/// Reads the nearest `Cargo.lock` (the project's or its workspace's).
pub(crate) fn check(project: &Project) -> Check {
  check_at(
    project
      .dir
      .ancestors()
      .map(|dir| dir.join("Cargo.lock"))
      .find(|path| path.is_file()),
  )
}

/// The check for the lock file found, if any.
fn check_at(lock: Option<PathBuf>) -> Check {
  let Some(lock) = lock else {
    return Check::warn(
      NAME,
      "no Cargo.lock in the project or above (run `cargo generate-lockfile`); id_effect versions not checked",
    );
  };
  match fs::read_to_string(&lock) {
    Ok(text) => check_lock(&text),
    Err(e) => Check::warn(NAME, format!("cannot read {}: {e}", lock.display())),
  }
}

fn check_lock(text: &str) -> Check {
  let crates = id_effect_packages(text);
  if crates.is_empty() {
    return Check::warn(NAME, "Cargo.lock lists no id_effect crate");
  }
  let mut versions: Vec<&str> = crates
    .iter()
    .map(|(_, v)| v.as_str())
    .collect::<BTreeSet<_>>()
    .into_iter()
    .collect();
  versions.sort_by_key(|v| version_key(v));
  let names_at = |version: &str| {
    crates
      .iter()
      .filter(|(_, v)| v == version)
      .map(|(n, _)| n.as_str())
      .collect::<BTreeSet<_>>()
      .into_iter()
      .collect::<Vec<_>>()
      .join(", ")
  };
  if let [version] = versions[..] {
    return Check::pass(NAME, format!("id_effect {version}: {}", names_at(version)));
  }
  let listed = versions
    .iter()
    .map(|v| format!("{v} ({})", names_at(v)))
    .collect::<Vec<_>>()
    .join(", ");
  let twice: Vec<&str> = crates
    .iter()
    .map(|(n, _)| n.as_str())
    .filter(|n| crates.iter().filter(|(m, _)| m == n).count() > 1)
    .collect::<BTreeSet<_>>()
    .into_iter()
    .collect();
  let copies = if twice.is_empty() {
    "id_effect crates are released together and must share a version".to_string()
  } else {
    format!(
      "{} in the build twice, whose types do not unify across copies",
      twice.join(", ")
    )
  };
  Check::fail(
    NAME,
    format!(
      "id_effect crates resolve to {} versions: {listed}; {copies}. Depend on one version and run `cargo update`",
      versions.len()
    ),
  )
}

/// `(name, version)` of every `[[package]]` named `id_effect` or `id_effect_*`.
fn id_effect_packages(lock: &str) -> Vec<(String, String)> {
  let entries = toml_entries(lock);
  let mut packages = Vec::new();
  let mut occurrence = None;
  let mut name: Option<String> = None;
  let mut version: Option<String> = None;
  for entry in entries.iter().filter(|e| e.table == "package") {
    if occurrence != Some(entry.occurrence) {
      if let (Some(n), Some(v)) = (name.take(), version.take()) {
        packages.push((n, v));
      }
      occurrence = Some(entry.occurrence);
    }
    match entry.key.as_str() {
      "name" => name = unquote(&entry.value),
      "version" => version = unquote(&entry.value),
      _ => {}
    }
  }
  if let (Some(n), Some(v)) = (name, version) {
    packages.push((n, v));
  }
  packages.retain(|(n, _)| n == "id_effect" || n.starts_with("id_effect_"));
  packages
}

/// `0.10.1` → [0, 10, 1], for numeric ordering (non-numeric parts sort first).
fn version_key(version: &str) -> Vec<u64> {
  version
    .split(['.', '-', '+'])
    .map(|p| p.parse().unwrap_or(0))
    .collect()
}

#[cfg(test)]
mod tests {
  use super::super::Status;
  use super::*;

  fn package(name: &str, version: &str) -> String {
    format!(
      "[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\ndependencies = [\n \"tokio\",\n]\n\n"
    )
  }

  fn lock(packages: &[(&str, &str)]) -> String {
    let mut text = "# This file is automatically @generated by Cargo.\nversion = 4\n\n".to_string();
    for (name, version) in packages {
      text.push_str(&package(name, version));
    }
    text
  }

  #[test]
  fn id_effect_packages_are_read_from_the_lock() {
    let text = lock(&[
      ("axum", "0.8.4"),
      ("id_effect", "0.7.0"),
      ("id_effect_kit", "0.7.0"),
      ("id_effectish", "1.0.0"),
    ]);
    assert_eq!(
      id_effect_packages(&text),
      [
        ("id_effect".to_string(), "0.7.0".to_string()),
        ("id_effect_kit".to_string(), "0.7.0".to_string())
      ]
    );
  }

  #[test]
  fn one_version_passes() {
    let check = check_lock(&lock(&[
      ("id_effect_kit", "0.7.0"),
      ("id_effect", "0.7.0"),
      ("serde", "1.0.0"),
    ]));
    assert_eq!(check.status, Status::Pass);
    assert_eq!(check.reason, "id_effect 0.7.0: id_effect, id_effect_kit");
  }

  #[test]
  fn a_crate_in_two_versions_fails_and_says_which() {
    let check = check_lock(&lock(&[
      ("id_effect", "0.10.0"),
      ("id_effect", "0.7.0"),
      ("id_effect_kit", "0.10.0"),
    ]));
    assert_eq!(check.status, Status::Fail);
    assert!(
      check.reason.starts_with(
        "id_effect crates resolve to 2 versions: 0.7.0 (id_effect), 0.10.0 (id_effect, id_effect_kit); id_effect in the build twice"
      ),
      "{}",
      check.reason
    );
  }

  #[test]
  fn different_crates_on_different_versions_fail_too() {
    let check = check_lock(&lock(&[
      ("id_effect", "0.7.0"),
      ("id_effect_axum", "0.6.2"),
    ]));
    assert_eq!(check.status, Status::Fail);
    assert!(
      check.reason.contains("released together"),
      "{}",
      check.reason
    );
  }

  #[test]
  fn no_id_effect_crate_or_no_lock_warns() {
    assert_eq!(
      check_lock(&lock(&[("serde", "1.0.0")])).status,
      Status::Warn
    );
    // Not via a temp dir: one under a workspace (ci-local sets TMPDIR to the repo's tmp/) would
    // find that workspace's lock.
    let check = check_at(None);
    assert_eq!(check.status, Status::Warn);
    assert!(
      check.reason.starts_with("no Cargo.lock"),
      "{}",
      check.reason
    );
  }

  #[test]
  fn the_lock_of_an_enclosing_workspace_counts() {
    let tmp = tempfile::tempdir().unwrap();
    fs::write(
      tmp.path().join("Cargo.lock"),
      lock(&[("id_effect", "0.6.0"), ("id_effect", "0.7.0")]),
    )
    .unwrap();
    let member = tmp.path().join("app");
    fs::create_dir(&member).unwrap();
    fs::write(member.join("Cargo.toml"), "[package]\nname = \"app\"\n").unwrap();
    let project = Project::load(&member).unwrap();
    assert_eq!(check(&project).status, Status::Fail);
  }
}
